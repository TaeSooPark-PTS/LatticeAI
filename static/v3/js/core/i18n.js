/* ============================================================================
 * Lattice AI v3 — i18n runtime
 *
 * Small, local-first dictionary loader for the SPA shell. The language choice is
 * stored on this device and applied without a backend round trip.
 * ========================================================================== */

export const LANG_KEY = "lt3-lang";
const DEFAULT_LANG = "en";
const SUPPORTED = new Set(["en", "ko"]);

function readLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return SUPPORTED.has(saved) ? saved : DEFAULT_LANG;
  } catch {
    return DEFAULT_LANG;
  }
}

let currentLang = readLang();

export function getI18nLanguage() {
  return currentLang;
}

export function setI18nLanguage(lang) {
  currentLang = SUPPORTED.has(lang) ? lang : DEFAULT_LANG;
  try { localStorage.setItem(LANG_KEY, currentLang); } catch {}
  document.documentElement.setAttribute("lang", currentLang);
  return currentLang;
}

export function languageOptions() {
  return [
    { key: "en", label: "English" },
    { key: "ko", label: "한국어" },
  ];
}

export function t(key, vars = {}) {
  const value = (DICT[currentLang] && DICT[currentLang][key]) || DICT.en[key] || key;
  return String(value).replace(/\{([a-zA-Z0-9_]+)\}/g, (_m, name) => (
    vars[name] == null ? "" : String(vars[name])
  ));
}

