import { chromium } from 'playwright';
import fs from 'node:fs';
const root = '/Users/parktaesoo/Downloads/Lattice AI/output/audits/v4.3.1-fixes';
const out = `${root}/screenshots`;
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 950 }, recordVideo: { dir: `${root}/gifs`, size: { width: 1024, height: 676 } } });
const page = await context.newPage();
page.setDefaultTimeout(15000);
await page.goto('http://127.0.0.1:8911/app', { waitUntil: 'networkidle' });
await page.screenshot({ path: `${out}/01-brain-start.png`, fullPage: true });
await page.click('text=Library');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: `${out}/02-library-models-honest-unavailable.png`, fullPage: true });
await page.click('text=Act');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: `${out}/03-act-agent-unavailable.png`, fullPage: true });
await page.goto('http://127.0.0.1:8911/app#/workflows', { waitUntil: 'networkidle' });
await page.waitForSelector('text=Workflow graph');
await page.screenshot({ path: `${out}/04-act-workflows-create-import-run.png`, fullPage: true });
await page.click('text=System');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: `${out}/05-system-storage-portability.png`, fullPage: true });
await context.close();
await browser.close();
